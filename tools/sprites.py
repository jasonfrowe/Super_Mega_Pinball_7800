#!/usr/bin/env python3
"""Sprites and the HUD font, in two 4K graphics blocks ($A000 and $C000).

Each sprite is drawn in 16-line strips (MARIA's zone height). A strip of w
bytes sits at one column of its block, its top line on page hi+15 and its
bottom line on page hi+0. The blocks sit above the $9000 and $B000 holes, so
a strip plotted across two zones reads zeros for the part outside it.

Writes src/gen/spr.bin (8K: $A000-$AFFF then $C000-$CFFF) and
src/gen/sprites.asm (the tables the game draws them with).
"""

from __future__ import annotations

import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import table as TB  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
GEN = ROOT / "src" / "gen"

BLOCKS = [0xA0, 0xC0]
blocks = [[bytearray(256) for _ in range(16)] for _ in BLOCKS]
used = [0, 0]
out = ["; Generated by tools/sprites.py. Do not edit.", ""]


def alloc(w, block=None):
    for bi in ([block] if block is not None else range(len(BLOCKS))):
        if used[bi] + w <= 256:
            lo = used[bi]
            used[bi] += w
            return bi, lo
    raise SystemExit("sprite blocks full")


def put_strip(pix, block=None):
    """pix: 16 rows of pixel values (0-3), width a multiple of 4. -> (lo, hi, w)"""
    w = len(pix[0]) // 4
    bi, lo = alloc(w, block)
    for y in range(16):
        for i in range(w):
            b = 0
            for k in range(4):
                b = (b << 2) | pix[y][i * 4 + k]
            blocks[bi][15 - y][lo + i] = b
    return lo, BLOCKS[bi], w


def strips_of(img):
    """Cut an image (rows of pixel values) into 16-line strips, padding."""
    h = len(img)
    w = len(img[0])
    n = (h + 15) // 16
    res = []
    for s in range(n):
        rows = []
        for y in range(16):
            yy = s * 16 + y
            rows.append(img[yy] if yy < h else [0] * w)
        res.append(rows)
    return res


