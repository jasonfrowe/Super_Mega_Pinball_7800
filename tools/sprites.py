FONT_ORDER = " 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ!-.:,'*+/#"


def font():
    # the font must start at column 0 of its block (CHARBASE = the block)
    assert used[0] == 0
    for ch in FONT_ORDER:
        g = GLYPHS[ch]
        pix = [[0] * 8 for _ in range(16)]
        for r in range(7):
            for c in range(8):
                lit = 1 <= c <= 5 and g[r][c - 1] == "1"
                y = 1 + r * 2
                if c == 7:
                    continue        # gap between characters
                pix[y][c] = 3 if lit else 1
                if lit:
                    pix[y + 1][c] = 2
        put_strip(pix, 0)
    out.append("; HUD font: character n of FONT_ORDER is index 2n")
    out.append(f"FONT_PAGE = ${BLOCKS[0]:02X}")
    tbl = [0] * 128
    for i, ch in enumerate(FONT_ORDER):
        tbl[ord(ch) & 127] = i * 2
    out.append("ascii2font")
    for i in range(32, 96, 16):
        out.append("    .byte " + ",".join(str(x) for x in tbl[i:i + 16]))


# ---------------------------------------------------------------------------
# Images: name -> list of frames; frame -> list of strips (lo, hi), plus
# per-frame width, x offset and y offset of the first strip (in 160A pixels /
# lines, relative to the object's anchor).
images = {}


def add_image(name, frames, block=None):
    """frames: list of (img rows, x_off, y_off). Every strip gets its own column."""
    recs = []
    for img, xo, yo in frames:
        w = len(img[0])
        if w % 4:
            img = [row + [0] * (4 - w % 4) for row in img]
        sts = [put_strip(s, block) for s in strips_of(img)]
        recs.append(dict(strips=sts, w=len(img[0]) // 4, xo=xo, yo=yo))
    images[name] = recs


def render(w, h, fn):
    return [[fn(x + 0.5, y + 0.5) for x in range(w)] for y in range(h)]


def ball():
    r = TB.BALL_R            # 6 units: 12 lines tall, 6 pixels wide

    def f(x, y):
        ux, uy = x * 2 - 6, y - 6          # 2 units per pixel across
        d = math.hypot(ux, uy)
        if d > r:
            return 0
        hl = math.hypot(ux + 1.5, uy + 2.0)
        if hl < 3.2:
            return 3
        if d > r - 0.9 and (ux + uy) > 0:
            return 1
        if (ux + uy) > 5:
            return 1
        return 2
    img = render(6, 12, f)
    add_image("ball", [(img, -3, -6)])


def flippers():
    n = 8
    L, R = TB.FLIP_LEN, TB.FLIP_RAD
    r0, r1 = R + 1.2, R - 0.8          # drawn tapered: thick at the pivot
    framesL, framesR = [], []
    for f in range(n):
        ang = TB.FLIP_UP + (TB.FLIP_REST - TB.FLIP_UP) * f / (n - 1)   # frame 0 = up
        a = math.radians(ang)
        tx, ty = L * math.cos(a), L * math.sin(a)
        # bounding box in units around the pivot
        xs = [-r0, tx + r1, tx - r1, r0]
        ys = [-r0, ty - r1, ty + r1, r0]
        x0, x1 = math.floor(min(xs) / 2) - 1, math.ceil(max(xs) / 2) + 1     # pixels
        y0, y1 = math.floor(min(ys)) - 1, math.ceil(max(ys)) + 1

        def shape(px, py, mirror):
            ux = (px + x0) * 2.0
            uy = py + y0
            if mirror:
                ux = -ux
            d, t = TB.seg_dist(ux, uy, 0, 0, tx, ty)
            rr = r0 + (r1 - r0) * t
            if d > rr:
                return 0
            # pivot screw
            if math.hypot(ux, uy) < 1.6:
                return 1
            # which side of the axis: rubber on the edges, white body
            if d > rr - 1.4:
                return 2
            return 3
        w, h = x1 - x0, y1 - y0
        imgL = render(w, h, lambda x, y: shape(x, y, False))
        framesL.append((imgL, x0, y0))
        # the right flipper: mirror around the pivot
        imgR = [list(reversed(row)) for row in imgL]
        # mirrored, its pixel columns run from -x1 .. -x0
        framesR.append((imgR, -x1 + 1, y0))
    add_image("flipl", framesL)
    add_image("flipr", framesR)


def plunger():
    # the plunger rod tip: 4 px wide, 16 lines (a knob and a spring below)
    def f(x, y):
        if y < 4:
            return 3 if 0.5 < x < 3.5 else 0
        if y < 6:
            return 2 if 0.5 < x < 3.5 else 0
        if int(y) % 3 == 0:
            return 2
        return 1 if 1 <= x < 3 else 0
    add_image("plunger", [(render(4, 16, f), -2, 0)])


def spinner():
    frames = []
    for k in range(4):
        th = [6, 4, 2, 1][k]          # apparent thickness as it turns

        def f(x, y, th=th):
            if abs(y - 4) <= th / 2 + 0.3:
                return 3 if abs(y - 4) < 0.6 else 2
            return 0
        frames.append((render(12, 8, f), 0, 0))
    add_image("spinner", frames)


font()
ball()
flippers()
plunger()
spinner()

# tables: every frame of every image numbered from 0 (IMG_x = its first);
# per frame: strips, -width&31, x offset, y offset, first strip; per strip lo, hi
names = list(images)
fr_n, fr_pw, fr_xo, fr_yo, fr_s0, st_lo, st_hi = [], [], [], [], [], [], []
for nm in names:
    out.append(f"IMG_{nm.upper()} = {len(fr_n)}")
    for r in images[nm]:
        fr_n.append(len(r["strips"]))
        fr_pw.append((-r["w"]) & 31)
        fr_xo.append(r["xo"] & 255)
        fr_yo.append(r["yo"] & 255)
        fr_s0.append(len(st_lo))
        for lo, hi, w in r["strips"]:
            st_lo.append(lo)
            st_hi.append(hi)
out.append(f"FLIP_FRAMES = {len(images['flipl'])}")
for nm, v in (("frm_n", fr_n), ("frm_pw", fr_pw), ("frm_xo", fr_xo), ("frm_yo", fr_yo), ("frm_s0", fr_s0),
              ("strip_lo", st_lo), ("strip_hi", st_hi)):
    out.append(f"{nm} .byte " + ",".join(str(x) for x in v))

GEN.mkdir(parents=True, exist_ok=True)
for i, blk in enumerate(blocks):
    (GEN / f"spr{i}.bin").write_bytes(b"".join(bytes(p) for p in blk))
(GEN / "spr_used.txt").write_text(" ".join(str(u) for u in used))
(GEN / "sprites.asm").write_text("\n".join(out) + "\n")
print(f"sprites: columns used {used} of 256; flipper strips/frame "
      f"{[len(r['strips']) for r in images['flipl']]}, widths {[r['w'] for r in images['flipl']]}")
